"""
Finds tree canopy in the satellite screenshot and writes candidate tree
positions (in screenshot pixels) to src/game/world/data/canopy.generated.ts.

Run from the repo root after replacing the screenshot:
    python3 scripts/map/extract_canopy.py

The game turns pixels into metres with MAP in data/mapSource.ts, so the output
stays valid if the map scale is adjusted later.
"""

import glob
import random
from pathlib import Path

from PIL import Image

SCREENSHOT = sorted(glob.glob("RULES/map/*.png"))[0]
OUTPUT = Path("src/game/world/data/canopy.generated.ts")
# Size of one sampling cell, in pixels (about 2.3 m at the map's scale).
CELL = 6
# Fraction of a cell that must be canopy-coloured to count.
MIN_COVER = 0.55
SEED = 2026


def is_canopy(r: int, g: int, b: int) -> bool:
    """Dark, saturated green: tree crowns. Fields are brown, roofs grey or blue."""
    return g > r + 4 and g > b + 6 and r + g + b < 330


def main() -> None:
    image = Image.open(SCREENSHOT).convert("RGB")
    width, height = image.size
    pixels = image.load()
    random.seed(SEED)

    cells = []
    for cy in range(0, height - CELL, CELL):
        for cx in range(0, width - CELL, CELL):
            hits = sum(
                is_canopy(*pixels[cx + dx, cy + dy]) for dy in range(CELL) for dx in range(CELL)
            )
            if hits / (CELL * CELL) >= MIN_COVER:
                # Jitter inside the cell so trees don't line up on a grid.
                cells.append((cx + random.uniform(0, CELL), cy + random.uniform(0, CELL)))

    lines = ",\n".join(f"  [{u:.0f}, {v:.0f}]" for u, v in cells)
    OUTPUT.write_text(
        "// Generated by scripts/map/extract_canopy.py from the satellite screenshot. Do not edit.\n"
        "// Candidate tree positions in screenshot pixels; vegetation.ts thins them out.\n\n"
        f"export const CANOPY_PX: readonly (readonly [number, number])[] = [\n{lines},\n];\n"
    )
    print(f"{len(cells)} canopy cells from {width}x{height} -> {OUTPUT}")


if __name__ == "__main__":
    main()
